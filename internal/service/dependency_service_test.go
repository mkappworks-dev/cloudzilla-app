func TestParseGoMod(t *testing.T) {
	input := `module example.com/myapp

go 1.21

require (
	github.com/go-chi/chi/v5 v5.0.10
	github.com/lib/pq v1.10.7
)

require github.com/stretchr/testify v1.8.4
`
	got := parseGoMod(input)
	want := []model.RepoDependency{
		{PackageMgr: "go", Package: "github.com/go-chi/chi/v5", Version: "v5.0.10", IsDev: false},
		{PackageMgr: "go", Package: "github.com/lib/pq", Version: "v1.10.7", IsDev: false},
		{PackageMgr: "go", Package: "github.com/stretchr/testify", Version: "v1.8.4", IsDev: false},
	}
	if len(got) != len(want) {
		t.Fatalf("parseGoMod: got %d deps, want %d\ngot: %+v", len(got), len(want), got)
	}
	for i, w := range want {
		if got[i].Package != w.Package || got[i].Version != w.Version || got[i].IsDev != w.IsDev {
			t.Errorf("parseGoMod[%d]: got %+v, want %+v", i, got[i], w)
		}
	}
}

func TestParsePackageJSON(t *testing.T) {
	input := `{
  "dependencies": {
    "express": "^4.18.2",
    "lodash": "4.17.21"
  },
  "devDependencies": {
    "jest": "^29.0.0"
  }
}`
	got := parsePackageJSON(input)
	if len(got) != 3 {
		t.Fatalf("parsePackageJSON: got %d deps, want 3\ngot: %+v", len(got), got)
	}
	devCount := 0
	for _, d := range got {
		if d.PackageMgr != "npm" {
			t.Errorf("PackageMgr should be npm, got %q", d.PackageMgr)
		}
		if d.IsDev {
			devCount++
		}
	}
	if devCount != 1 {
		t.Errorf("expected 1 dev dependency, got %d", devCount)
	}
}

func TestParseRequirementsTxt(t *testing.T) {
	input := `# This file was autogenerated
requests==2.31.0
flask>=2.3.0
numpy
# a comment
pytest~=7.4.0
`
	got := parseRequirementsTxt(input)
	if len(got) != 4 {
		t.Fatalf("parseRequirementsTxt: got %d deps, want 4\ngot: %+v", len(got), got)
	}
	for _, d := range got {
		if d.PackageMgr != "pip" {
			t.Errorf("PackageMgr should be pip, got %q", d.PackageMgr)
		}
	}
	if got[0].Package != "requests" || got[0].Version != "2.31.0" {
		t.Errorf("first dep wrong: %+v", got[0])
	}
	if got[2].Package != "numpy" || got[2].Version != "" {
		t.Errorf("numpy should have empty version: %+v", got[2])
	}
}

func TestParseCargoToml(t *testing.T) {
	input := `[package]
name = "myapp"
version = "0.1.0"

[dependencies]
serde = "1.0"
tokio = { version = "1.28", features = ["full"] }

[dev-dependencies]
criterion = "0.5"
`
	got := parseCargoToml(input)
	if len(got) != 3 {
		t.Fatalf("parseCargoToml: got %d deps, want 3\ngot: %+v", len(got), got)
	}
	for _, d := range got {
		if d.PackageMgr != "cargo" {
			t.Errorf("PackageMgr should be cargo, got %q", d.PackageMgr)
		}
	}
	if got[0].Package != "serde" || got[0].IsDev {
		t.Errorf("serde should be non-dev: %+v", got[0])
	}
	if got[2].Package != "criterion" || !got[2].IsDev {
		t.Errorf("criterion should be dev: %+v", got[2])
	}
}
